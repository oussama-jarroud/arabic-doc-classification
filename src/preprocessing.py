_MULTIPLE_WHITESPACE_REGEX: re.Pattern[str] = re.compile(r"\s+")
_STEMMER: ISRIStemmer = ISRIStemmer()


def remove_diacritics(text: str) -> str:
    """Strip short vowels and diacritical marks to standardize phonetic variations."""
    return _DIACRITICS_REGEX.sub("", text)


def remove_tatweel(text: str) -> str:
    """Remove typographic kashida elongation characters to recover canonical token forms."""
    return text.replace(_TATWEEL_CHAR, "")


def normalize_hamza_alef(text: str) -> str:
    """Unify orthographic letter variants into single base graphemes."""
    normalized = _ALEF_HAMZA_REGEX.sub(_BARE_ALEF_CHAR, text)
    normalized = normalized.replace(_TA_MARBUTA_CHAR, _HA_CHAR)
    normalized = normalized.replace(_ALEF_MAQSURA_CHAR, _YA_CHAR)
    return normalized


def remove_non_arabic_punct(text: str) -> str:
    """Filter out non-Arabic scripts, punctuation, and numeric noise to isolate lexical content."""
    cleaned = _NON_ARABIC_REGEX.sub(" ", text)
    return _MULTIPLE_WHITESPACE_REGEX.sub(" ", cleaned).strip()


def remove_stopwords(text: str) -> str:
    """Eliminate non-discriminative syntactic function words to concentrate lexical information."""
    tokens = text.split()
    return " ".join(token for token in tokens if token not in ARABIC_STOPWORDS)


def isri_stem(text: str) -> str:
    """Reduce inflected Arabic words to root lemmas to collapse vocabulary dimensionality."""
    tokens = text.split()
    return " ".join(_STEMMER.stem(token) for token in tokens)


STEP_REGISTRY: dict[str, Callable[[str], str]] = {
    "remove_diacritics": remove_diacritics,
    "remove_tatweel": remove_tatweel,
    "normalize_hamza_alef": normalize_hamza_alef,
    "remove_non_arabic_punct": remove_non_arabic_punct,
    "remove_stopwords": remove_stopwords,
    "isri_stem": isri_stem,
}


def compose_pipeline(step_names: list[str]) -> Callable[[str], str]:
    """Compose ordered pure transformation functions into a unified deterministic pipeline."""
    for name in step_names:
        if name not in STEP_REGISTRY:
            available = list(STEP_REGISTRY.keys())
            raise KeyError(f"Unknown preprocessing step: '{name}'. Available steps: {available}")
    steps = [STEP_REGISTRY[name] for name in step_names]

    def pipeline(text: str) -> str:
        current = text
        for step in steps:
            current = step(current)
        return current

    return pipeline


def get_pipeline(
    pipeline_name: str,
    config: dict[str, Any] | Path | str | None = None,
) -> Callable[[str], str]:
    """Instantiate a named preprocessing pipeline defined in centralized YAML configuration."""
    cfg = load_config(config) if isinstance(config, (str, Path)) or config is None else config
    pipelines = cfg.get("preprocessing_pipelines", {})
    if pipeline_name not in pipelines:
        available = list(pipelines.keys())
        raise KeyError(
            f"Unknown pipeline name: '{pipeline_name}'. Available pipelines: {available}"
        )
    step_names = list(pipelines[pipeline_name])
    return compose_pipeline(step_names)


def batch_preprocess_texts(
    texts: list[str],
    pipeline_fn: Callable[[str], str],
    chunk_size: int = 500,
    n_jobs: int = -1,
) -> list[str]:
    """Apply transformation pipeline across texts in parallel to accelerate batch processing."""
    if not texts:
        return []
    if len(texts) < 50:
        return [pipeline_fn(t) for t in texts]
    return Parallel(n_jobs=n_jobs, batch_size=chunk_size)(delayed(pipeline_fn)(t) for t in texts)

